using System;
using System.IO;
using EscapeFromBorderlands.Client;

var checks = 0;
void Check(bool condition, string reason)
{
    checks++;
    if (!condition) throw new InvalidOperationException(reason);
}

var folder = Path.Combine(Path.GetTempPath(), "efb-guid-migration-tests-" + Guid.NewGuid().ToString("N"));
Directory.CreateDirectory(folder);
try
{
    var old = Path.Combine(folder, "com.tkw.escapefromborderlands.client.cfg");
    var interim = Path.Combine(folder, "com.tkw.escapefromborderlands.cfg");
    var current = Path.Combine(folder, "com.tKwNw.escapefromborderlands.cfg");
    const string oldText = "[Status icons]\nEnabled = false\nHorizontal offset = 42\n[Legendary grenades]\nHoly Hand Grenade draw sound volume = 0.25\n";

    // Empty destination: full preservation and reload can occur before Bind.
    File.WriteAllText(old, oldText);
    Check(LegacyClientConfigMigration.Migrate(folder, current) == 3, "Original config did not import all three entries");
    Check(File.ReadAllText(current).Contains("Enabled = false"), "Disabled HUD was not preserved");
    Check(File.ReadAllText(current).Contains("Holy Hand Grenade draw sound volume = 0.25"), "Audio volume missing");
    Check(File.Exists(old), "Old config unexpectedly removed");

    // Subsequent launches must be entirely idempotent.
    var before = File.ReadAllText(current);
    Check(LegacyClientConfigMigration.Migrate(folder, current) == 0, "Second migration should import zero entries");
    Check(File.ReadAllText(current) == before, "Second migration changed the file");

    // BepInEx can pre-create a destination; existing user values take priority.
    File.WriteAllText(current, "# Generated by BepInEx\n[Status icons]\nEnabled = true\n");
    Check(LegacyClientConfigMigration.Migrate(folder, current) == 2, "Partially populated new config should merge two missing keys");
    var merged = File.ReadAllText(current);
    Check(merged.Contains("Enabled = true") && !merged.Contains("Enabled = false"), "Existing current HUD setting was overwritten");
    Check(merged.Contains("Horizontal offset = 42"), "HUD offset was not merged");
    Check(merged.Contains("Holy Hand Grenade draw sound volume = 0.25"), "Audio setting not merged");
    Check(File.Exists(current + ".pre-0.30-migration.bak"), "Pre-migration backup not created");

    // If an intermediate shortened-GUID config was used, take its values first.
    File.Delete(current);
    File.WriteAllText(interim, "[Status icons]\nEnabled = true\n[Legendary grenades]\nHoly Hand Grenade draw sound volume = 0.75\n");
    Check(LegacyClientConfigMigration.Migrate(folder, current) == 3, "Intermediate config should take priority and older-only key should still import");
    merged = File.ReadAllText(current);
    Check(merged.Contains("Enabled = true") && !merged.Contains("Enabled = false"), "Intermediate user preference not prioritized");
    Check(merged.Contains("Holy Hand Grenade draw sound volume = 0.75"), "Intermediate sound level not prioritized");
    Check(merged.Contains("Horizontal offset = 42"), "Older-only key not retained");
    Check(File.Exists(interim), "Intermediate config was removed");

    Console.WriteLine($"PASS: {checks} migration assertions (original, pre-created destination, merge precedence, backup and idempotency)");
}
finally
{
    Directory.Delete(folder, recursive: true);
}
